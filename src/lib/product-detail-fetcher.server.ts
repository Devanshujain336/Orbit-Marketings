/**
 * Server-only single-product detail scraper and fact verification engine for Orbit.
 * Fetches an individual product page URL via Firecrawl (or fallback) without re-scraping
 * the whole website, extracts verified product facts, and caches results to prevent redundant calls.
 */

import { normalizeUrl, scrapeWithFirecrawl, fallbackDirectScrape } from "./firecrawl.server";
import type { ProductBrain } from "./gemini-brand-brain.server";

export type VerifiedProductDetails = {
  url: string;
  fetchedSuccessfully: boolean;
  productName?: string | undefined;
  description: string;
  features: string[];
  specifications: string[];
  materialsOrIngredients: string[];
  explicitClaims: string[];
  rawPrice?: string | null | undefined;
  rawCurrency?: string | null | undefined;
};

// In-memory cache keyed by canonical URL to prevent re-scraping across concept generations
const productDetailsCache = new Map<string, VerifiedProductDetails>();

export function getCachedProductDetails(url: string): VerifiedProductDetails | undefined {
  return productDetailsCache.get(normalizeProductUrl(url));
}

export function setCachedProductDetails(url: string, details: VerifiedProductDetails): void {
  productDetailsCache.set(normalizeProductUrl(url), details);
}

export function clearProductDetailsCache(): void {
  productDetailsCache.clear();
}

/**
 * Filter out catalog-level placeholder strings generated by initial scrapers
 */
const PLACEHOLDER_FEATURES = new Set([
  "verified genuine brand item",
  "direct online ordering",
  "high durability & design",
  "direct from brand",
  "genuine brand item",
  "in-stock online",
  "fast delivery",
  "authentic brand quality",
  "genuine product",
  "available online",
  "quality guaranteed",
  "authentic brand product",
  "premium design & craftsmanship",
  "official warranty & return support",
]);

export function filterOutPlaceholderFeatures(items?: string[]): string[] {
  if (!items || !Array.isArray(items)) return [];
  return items.filter((item) => {
    const clean = String(item || "").trim().toLowerCase();
    return clean.length > 0 && !PLACEHOLDER_FEATURES.has(clean);
  });
}

/**
 * Normalizes a product URL, stripping transient marketing and session query parameters
 */
export function normalizeProductUrl(raw: string): string {
  try {
    const u = normalizeUrl(raw);
    const searchParams = new URLSearchParams(u.search);
    const trackingParams = [
      "utm_source",
      "utm_medium",
      "utm_campaign",
      "utm_term",
      "utm_content",
      "ref",
      "fbclid",
      "gclid",
      "_ga",
      "_gl",
    ];
    trackingParams.forEach((p) => searchParams.delete(p));
    u.search = searchParams.toString() ? `?${searchParams.toString()}` : "";
    return u.toString();
  } catch {
    return (raw || "").trim();
  }
}

function toStringArray(val: unknown): string[] {
  if (!Array.isArray(val)) return [];
  return val
    .map((item) => String(item ?? "").trim())
    .filter((item) => item.length > 0);
}

/**
 * Deterministic fallback extractor using JSON-LD schema and markdown section patterns
 */
function extractDeterministicProductDetails(
  page: { markdown: string; html?: string | undefined; title?: string | undefined; description?: string | undefined },
  url: string,
  basicProduct?: Partial<ProductBrain> | undefined
): VerifiedProductDetails {
  let description = page.description || basicProduct?.description || "";
  const features: string[] = [];
  const specifications: string[] = [];
  const materialsOrIngredients: string[] = [];
  const explicitClaims: string[] = [];

  // 1. Inspect JSON-LD from HTML if available
  if (page.html) {
    const jsonLdRegex = /<script[^>]+type=["']application\/ld\+json["'][^>]*>([\s\S]*?)<\/script>/gi;
    let match: RegExpExecArray | null;
    while ((match = jsonLdRegex.exec(page.html)) !== null) {
      if (!match[1]) continue;
      try {
        const parsed = JSON.parse(match[1]);
        const items = Array.isArray(parsed)
          ? parsed
          : parsed["@type"] === "Product"
            ? [parsed]
            : Array.isArray(parsed["@graph"])
              ? parsed["@graph"].filter((g: any) => g && g["@type"] === "Product")
              : [];

        for (const item of items) {
          if (!item || typeof item !== "object") continue;
          if (item.description && typeof item.description === "string" && item.description.length > description.length) {
            description = item.description.trim();
          }
          if (item.material) {
            if (typeof item.material === "string") materialsOrIngredients.push(item.material.trim());
            else if (Array.isArray(item.material)) materialsOrIngredients.push(...toStringArray(item.material));
          }
          if (Array.isArray(item.additionalProperty)) {
            for (const prop of item.additionalProperty) {
              if (prop && prop.name && prop.value) {
                specifications.push(`${prop.name}: ${prop.value}`);
              }
            }
          }
        }
      } catch {
        // ignore parse error
      }
    }
  }

  // 2. Scan Markdown for structured section headers
  const lines = page.markdown.split("\n");
  let currentSection: "materials" | "specs" | "features" | "claims" | null = null;

  for (const rawLine of lines) {
    const line = rawLine.trim();
    if (!line) continue;

    // Detect section headers
    if (/^#{1,4}\s+(materials?|fabric|composition|ingredients|what's inside)/i.test(line)) {
      currentSection = "materials";
      continue;
    } else if (/^#{1,4}\s+(specifications?|specs|dimensions|sizing|measurements|tech specs|details|care)/i.test(line)) {
      currentSection = "specs";
      continue;
    } else if (/^#{1,4}\s+(features|highlights|key features|overview|benefits)/i.test(line)) {
      currentSection = "features";
      continue;
    } else if (/^#{1,4}\s+(certifications?|claims|guarantee|standards)/i.test(line)) {
      currentSection = "claims";
      continue;
    } else if (/^#{1,4}\s+/i.test(line)) {
      // Another header: reset section
      currentSection = null;
      continue;
    }

    // Capture bullet points or clean text lines within section
    if (currentSection && (line.startsWith("- ") || line.startsWith("* ") || line.startsWith("• "))) {
      const item = line.replace(/^[-*•]\s+/, "").trim();
      if (item.length > 2 && item.length < 240) {
        if (currentSection === "materials" && !materialsOrIngredients.includes(item)) {
          materialsOrIngredients.push(item);
        } else if (currentSection === "specs" && !specifications.includes(item)) {
          specifications.push(item);
        } else if (currentSection === "features" && !features.includes(item)) {
          features.push(item);
        } else if (currentSection === "claims" && !explicitClaims.includes(item)) {
          explicitClaims.push(item);
        }
      }
    }
  }

  return {
    url,
    fetchedSuccessfully: true,
    productName: basicProduct?.name,
    description: description || basicProduct?.description || "",
    features: filterOutPlaceholderFeatures(features.length > 0 ? features : basicProduct?.features),
    specifications: specifications.slice(0, 15),
    materialsOrIngredients: materialsOrIngredients.slice(0, 15),
    explicitClaims: explicitClaims.slice(0, 10),
  };
}

/**
 * Call direct Gemini API to extract verified factual details from the product page
 */
async function callGeminiExtractor(
  pageText: string,
  productName: string,
  rawApiKey: string
): Promise<{
  description?: string;
  features?: string[];
  specifications?: string[];
  materialsOrIngredients?: string[];
  explicitClaims?: string[];
} | null> {
  const apiKey = rawApiKey.trim().replace(/^["']|["']$/g, "").trim();
  const models = [
    "gemini-3.8-flash",
    "gemini-3.7-flash",
    "gemini-3.5-flash",
    "gemini-flash-latest",
    "gemini-2.5-flash",
  ];

  const systemPrompt = `You are Orbit's Product Fact Extraction & Verification Engine.
Your task is to extract ONLY explicitly stated factual product details from the scraped single product page text.

CRITICAL ZERO-HALLUCINATION RULES:
1. ONLY extract details that are explicitly written on this product page.
2. DO NOT invent, assume, extrapolate, or guess any features, specifications, materials, ingredients, or claims.
3. If ingredients or materials are not explicitly stated, return an empty array: [].
4. If specifications (measurements, dimensions, technical specs, weight, volume, sizing, care instructions) are not mentioned, return an empty array: [].
5. If bulleted features are not mentioned, return an empty array: [].
6. For 'explicitClaims', ONLY include verifiable guarantees, certifications, or factual claims explicitly printed on the page (e.g. '100% Grass-Fed', 'Gluten-Free', 'UPF 50+', 'Non-GMO Project Verified', 'Lifetime Warranty'). Do NOT create marketing slogans.
7. Return strict minified JSON conforming to:
{
  "description": "explicitly stated product description or empty string",
  "features": ["array of explicitly listed feature bullets"],
  "specifications": ["array of explicitly stated specs, measurements, sizing, or technical metrics"],
  "materialsOrIngredients": ["array of explicitly stated ingredients, fabric breakdown, or materials"],
  "explicitClaims": ["array of explicitly stated certifications, dietary claims, guarantees, or factual claims"]
}`;

  const userPrompt = `Target Product Name: ${productName}

Scraped Product Page Content:
${pageText.slice(0, 16000)}

Extract verified factual JSON now:`;

  for (const model of models) {
    try {
      const url = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${encodeURIComponent(apiKey)}`;
      const res = await fetch(url, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          systemInstruction: { parts: [{ text: systemPrompt }] },
          contents: [{ parts: [{ text: userPrompt }] }],
          generationConfig: {
            responseMimeType: "application/json",
            temperature: 0.1,
          },
        }),
      });

      if (!res.ok) {
        if (res.status === 403 || res.status === 429) break;
        continue;
      }

      const json = (await res.json()) as {
        candidates?: Array<{ content?: { parts?: Array<{ text?: string }> } }>;
      };

      const rawText = json.candidates?.[0]?.content?.parts?.[0]?.text ?? "";
      const cleaned = rawText.replace(/```json/gi, "").replace(/```/g, "").trim();
      const start = cleaned.indexOf("{");
      const end = cleaned.lastIndexOf("}");
      if (start !== -1 && end !== -1) {
        return JSON.parse(cleaned.slice(start, end + 1));
      }
    } catch (err) {
      console.warn(`Gemini product extraction error with ${model}:`, err);
    }
  }

  return null;
}

/**
 * Call Groq API to extract verified factual details from the product page
 */
async function callGroqExtractor(
  pageText: string,
  productName: string,
  rawApiKey: string
): Promise<{
  description?: string;
  features?: string[];
  specifications?: string[];
  materialsOrIngredients?: string[];
  explicitClaims?: string[];
} | null> {
  const apiKey = rawApiKey.trim().replace(/^["']|["']$/g, "").trim();
  const models = ["openai/gpt-oss-120b", "openai/gpt-oss-20b", "qwen/qwen3.8-27b"];

  const systemPrompt = `You are Orbit's Product Fact Extraction & Verification Engine.
Your task is to extract ONLY explicitly stated factual product details from the scraped single product page text.

CRITICAL ZERO-HALLUCINATION RULES:
1. ONLY extract details that are explicitly written on this product page.
2. DO NOT invent, assume, extrapolate, or guess any features, specifications, materials, ingredients, or claims.
3. If ingredients or materials are not explicitly stated, return an empty array: [].
4. If specifications (measurements, dimensions, technical specs, weight, volume, sizing, care instructions) are not mentioned, return an empty array: [].
5. If bulleted features are not mentioned, return an empty array: [].
6. For 'explicitClaims', ONLY include verifiable guarantees, certifications, or factual claims explicitly printed on the page.
7. Return strict minified JSON conforming to:
{
  "description": "explicitly stated product description or empty string",
  "features": ["array of explicitly listed feature bullets"],
  "specifications": ["array of explicitly stated specs, measurements, sizing, or technical metrics"],
  "materialsOrIngredients": ["array of explicitly stated ingredients, fabric breakdown, or materials"],
  "explicitClaims": ["array of explicitly stated certifications, dietary claims, guarantees, or factual claims"]
}`;

  const userPrompt = `Target Product Name: ${productName}

Scraped Product Page Content:
${pageText.slice(0, 16000)}

Extract verified factual JSON now:`;

  for (const model of models) {
    try {
      const res = await fetch("https://api.groq.com/openai/v1/chat/completions", {
        method: "POST",
        headers: {
          Authorization: `Bearer ${apiKey}`,
          "Content-Type": "application/json",
        },
        body: JSON.stringify({
          model,
          messages: [
            { role: "system", content: systemPrompt },
            { role: "user", content: userPrompt },
          ],
          response_format: { type: "json_object" },
          temperature: 0.1,
        }),
      });

      if (!res.ok) continue;

      const json = (await res.json()) as {
        choices?: Array<{ message?: { content?: string } }>;
      };

      const rawText = json.choices?.[0]?.message?.content ?? "";
      const cleaned = rawText.replace(/```json/gi, "").replace(/```/g, "").trim();
      const start = cleaned.indexOf("{");
      const end = cleaned.lastIndexOf("}");
      if (start !== -1 && end !== -1) {
        return JSON.parse(cleaned.slice(start, end + 1));
      }
    } catch (err) {
      console.warn(`Groq product extraction error with ${model}:`, err);
    }
  }

  return null;
}

/**
 * Main function: Fetches an individual product page URL via Firecrawl (or fallback)
 * and extracts factual description, features, specifications, materials/ingredients, and claims.
 */
export async function fetchAndExtractProductDetails(
  productUrl: string,
  basicProduct?: Partial<ProductBrain>
): Promise<VerifiedProductDetails> {
  const canonicalUrl = normalizeProductUrl(productUrl);

  // 1. Check in-memory cache to prevent re-scraping
  if (productDetailsCache.has(canonicalUrl)) {
    return productDetailsCache.get(canonicalUrl)!;
  }

  let parsedUrl: URL;
  try {
    parsedUrl = normalizeUrl(canonicalUrl);
  } catch {
    const unverified: VerifiedProductDetails = {
      url: canonicalUrl,
      fetchedSuccessfully: false,
      productName: basicProduct?.name,
      description: basicProduct?.description || "",
      features: filterOutPlaceholderFeatures(basicProduct?.features),
      specifications: [],
      materialsOrIngredients: [],
      explicitClaims: [],
    };
    return unverified;
  }

  // 2. Fetch the individual product page
  const firecrawlKey = (process.env["FIRECRAWL_API_KEY"] || "").trim().replace(/^["']|["']$/g, "").trim();
  let pageData: {
    markdown: string;
    html?: string | undefined;
    title?: string | undefined;
    description?: string | undefined;
  } | null = null;

  if (firecrawlKey && firecrawlKey.length > 10 && firecrawlKey !== "YOUR_FIRECRAWL_API_KEY") {
    pageData = await scrapeWithFirecrawl(canonicalUrl, firecrawlKey);
  }

  if (!pageData) {
    try {
      const direct = await fallbackDirectScrape(parsedUrl, 10000);
      pageData = {
        markdown: direct.markdown,
        html: direct.html,
        title: direct.title,
        description: direct.description,
      };
    } catch (err) {
      console.warn(`Could not scrape individual product page ${canonicalUrl}:`, err);
    }
  }

  // If page could not be fetched, continue gracefully with basic product info (Rule 6)
  if (!pageData || (!pageData.markdown && !pageData.html)) {
    const unverified: VerifiedProductDetails = {
      url: canonicalUrl,
      fetchedSuccessfully: false,
      productName: basicProduct?.name,
      description: basicProduct?.description || "",
      features: filterOutPlaceholderFeatures(basicProduct?.features),
      specifications: [],
      materialsOrIngredients: [],
      explicitClaims: [],
    };
    return unverified;
  }

  // 3. Extract verified product attributes using Gemini (or Groq fallback)
  const geminiKey = process.env["GEMINI_API_KEY"];
  const groqKey = process.env["GROQ_API_KEY"];
  let verifiedDetails: VerifiedProductDetails | null = null;

  if (geminiKey && geminiKey.trim().length > 8 && geminiKey !== "YOUR_GEMINI_API_KEY") {
    const aiExtracted = await callGeminiExtractor(
      pageData.markdown || pageData.html || "",
      basicProduct?.name || pageData.title || "Product",
      geminiKey
    );

    if (aiExtracted) {
      verifiedDetails = {
        url: canonicalUrl,
        fetchedSuccessfully: true,
        productName: basicProduct?.name || pageData.title,
        description: (aiExtracted.description && aiExtracted.description.trim().length > 0)
          ? aiExtracted.description.trim()
          : (pageData.description || basicProduct?.description || ""),
        features: filterOutPlaceholderFeatures(toStringArray(aiExtracted.features)),
        specifications: toStringArray(aiExtracted.specifications),
        materialsOrIngredients: toStringArray(aiExtracted.materialsOrIngredients),
        explicitClaims: toStringArray(aiExtracted.explicitClaims),
      };
    }
  }

  // Fallback to Groq if Gemini failed or was unconfigured
  if (!verifiedDetails && groqKey && groqKey.trim().length > 8 && groqKey !== "YOUR_GROQ_API_KEY") {
    const aiExtracted = await callGroqExtractor(
      pageData.markdown || pageData.html || "",
      basicProduct?.name || pageData.title || "Product",
      groqKey
    );

    if (aiExtracted) {
      verifiedDetails = {
        url: canonicalUrl,
        fetchedSuccessfully: true,
        productName: basicProduct?.name || pageData.title,
        description: (aiExtracted.description && aiExtracted.description.trim().length > 0)
          ? aiExtracted.description.trim()
          : (pageData.description || basicProduct?.description || ""),
        features: filterOutPlaceholderFeatures(toStringArray(aiExtracted.features)),
        specifications: toStringArray(aiExtracted.specifications),
        materialsOrIngredients: toStringArray(aiExtracted.materialsOrIngredients),
        explicitClaims: toStringArray(aiExtracted.explicitClaims),
      };
    }
  }

  // Fallback to deterministic extraction if Gemini was unavailable or returned empty
  if (!verifiedDetails) {
    verifiedDetails = extractDeterministicProductDetails(pageData, canonicalUrl, basicProduct);
  }

  // Cache the result
  productDetailsCache.set(canonicalUrl, verifiedDetails);

  return verifiedDetails;
}
